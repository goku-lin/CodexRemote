import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createServer} from 'node:net';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('archive snapshots, restore, desktop idle and cancelled history stay consistent across refreshes', {timeout:15000}, async t=>{
  const directory=await mkdtemp(path.join(os.tmpdir(),'relay-thread-sync-'));
  const reservation=createServer();await new Promise(resolve=>reservation.listen(0,'127.0.0.1',resolve));
  const port=reservation.address().port;await new Promise(resolve=>reservation.close(resolve));
  const child=spawn(process.execPath,['server.mjs'],{cwd:new URL('..',import.meta.url),windowsHide:true,
    env:{...process.env,HOST:'127.0.0.1',PORT:String(port),CODEX_RELAY_TOKEN:'thread-sync-fixture',CODEX_RELAY_NO_EMBEDDED:'1',CODEX_RELAY_DATA_DIR:directory}});
  t.after(async()=>{const stopped=new Promise(resolve=>child.once('exit',resolve));child.kill();await stopped;
    assert.equal(path.dirname(path.resolve(directory)),path.resolve(os.tmpdir()));await rm(directory,{recursive:true,force:true});});
  await new Promise((resolve,reject)=>{child.once('error',reject);child.stdout.on('data',chunk=>{if(String(chunk).includes('listening'))resolve();});});
  const base=`http://127.0.0.1:${port}`;
  const runner=async body=>{const response=await fetch(base+'/api/runner/local/events',{method:'POST',headers:{'content-type':'application/json','x-codex-relay-token':'thread-sync-fixture'},body:JSON.stringify(body)});assert.equal(response.status,202);};
  const snapshot=async()=>await(await fetch(base+'/api/bootstrap')).json();
  const threads=['a','b'].map(id=>({id,name:id,cwd:directory,createdAt:1,updatedAt:2,status:{type:'notLoaded'}}));
  await runner({type:'thread_list',threads,complete:true,observedAt:100});
  let sessions=(await snapshot()).sessions;
  const a=sessions.find(s=>s.threadId==='a').id,b=sessions.find(s=>s.threadId==='b').id;
  const history={type:'thread_history',sessionId:a,threadId:'a',turns:[{id:'turn',status:'inProgress',startedAt:1000}],items:[{id:'u',role:'user',turnId:'turn',text:'Check',at:1000}],turnCount:1,messageCount:1};
  await runner(history);
  await runner({sessionId:a,origin:'desktop',at:1100,message:{method:'turn/started',params:{threadId:'a',turn:{id:'turn'}}}});
  await runner({type:'native_status',connected:false,threadIds:['a'],activeTurns:{}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'running');
  await runner({type:'native_status',connected:true,capabilities:{events:true},threadIds:['b'],activeTurns:{}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'running');
  await runner({type:'native_status',connected:true,capabilities:{events:true},threadIds:['a'],activeTurns:{}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'synced');
  await runner(history);
  assert.notEqual((await snapshot()).sessions.find(s=>s.id===a).status,'running');
  history.turns[0]={...history.turns[0],status:'interrupted',completedAt:2000};await runner(history);
  await runner({type:'native_status',connected:true,capabilities:{events:true},threadIds:['a'],activeTurns:{a:'turn'}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'interrupted');
  const activeState={threadId:'a',status:{type:'active',activeFlags:[]},turnId:'turn',observedAt:Date.now()+1,epoch:'runtime',revision:1};
  await runner({type:'native_status',connected:true,capabilities:{events:true},threadIds:['a'],threadStates:[activeState],activeTurns:{a:'turn'}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'running','confirmed Desktop activity must override a stale interrupted history');
  await runner({...history,desktopRuntime:{...activeState,status:{type:'idle'},turnId:null,observedAt:2000,revision:0}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'running');
  const runningHistory=await(await fetch(base+`/api/sessions/${a}/history`)).json();assert.equal(runningHistory.turns.at(-1).status,'inProgress');
  await runner({type:'native_status',connected:false,threadIds:['a'],threadStates:[],activeTurns:{}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'running','loss of the connection must not invent an interruption');
  await runner({type:'native_status',connected:true,capabilities:{events:true},threadIds:['a'],threadStates:[{...activeState,status:{type:'idle'},turnId:null,observedAt:activeState.observedAt+1,revision:2}],activeTurns:{}});
  assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'synced');
  await runner(history);assert.equal((await snapshot()).sessions.find(s=>s.id===a).status,'interrupted');
  await runner({type:'thread_list',threads:[threads[0]],complete:false,observedAt:2100});
  assert.equal((await snapshot()).sessions.length,2);
  await runner({sessionId:b,origin:'desktop',at:3000,message:{method:'thread/archived',params:{threadId:'b'}}});
  assert.equal((await snapshot()).sessions.length,1);
  assert.equal((await fetch(base+`/api/sessions/${b}/history`)).status,404);
  await runner({type:'thread_list',threads,complete:true,observedAt:2500});
  assert.equal((await snapshot()).sessions.length,1,'a list captured before archive must not restore it');
  await runner({type:'thread_list',threads:[threads[0]],complete:true,observedAt:3100});
  await runner({sessionId:b,origin:'desktop',at:4000,message:{method:'thread/unarchived',params:{threadId:'b'}}});
  assert.equal((await snapshot()).sessions.length,2);
  await runner({type:'thread_list',threads:[threads[0]],complete:true,observedAt:5000});
  assert.equal((await snapshot()).sessions.length,1,'complete discovery removes a missed archive notification');
  await runner({type:'thread_list',threads,complete:true,observedAt:6000});
  assert.equal((await snapshot()).sessions.length,2,'restored threads reappear in complete discovery');
  await runner({type:'thread_list',threads:[],complete:true,observedAt:7000});
  assert.equal((await snapshot()).sessions.length,0);
  assert.equal((await snapshot()).projects.length,0);
});
