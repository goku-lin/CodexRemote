test('model and effort selection propagates, permissions respect device requirements', () => {
  const selected = validateOptions({model:'fixture',effort:'max',permission:'workspace-write'}, catalog);
  assert.deepEqual(threadOptions(selected), {model:'fixture',approvalPolicy:'on-request',sandbox:'workspace-write'});
  assert.deepEqual(turnOptions({...selected,cwd:'C:/project'}), {model:'fixture',effort:'max',cwd:'C:/project',approvalPolicy:'on-request',sandboxPolicy:{type:'workspaceWrite',networkAccess:false,writableRoots:['C:/project']}});
  assert.deepEqual(turnOptions({}), {});
  assert.throws(()=>validateOptions({model:'invented'},catalog));
  assert.throws(()=>validateOptions({model:'fixture',effort:'invented'},catalog));
  assert.throws(()=>validateOptions({permission:'danger-full-access'}, {requirements:{allowedSandboxModes:['read-only']}}));
});

test('image references retain real attachments and reject disguised files', () => {
  assert.equal(decodeImage(png).mime,'image/png');
  assert.equal(decodeImage(png.replace('image/png','image/jpeg')).mime,'image/png');
  assert.throws(()=>decodeImage('data:image/png;base64,'+Buffer.from('not an image').toString('base64')));
  const refs = imageReferences('![result](C:/path with spaces/result.png)\n<image path="C:\\Temp\\input.png"></image>',[{type:'image',url:png}]);
  assert.equal(refs.length,3);
  assert.deepEqual(imageReferences('[参考](file:///D:/with%20spaces/ref.png)\n[网页](https://example.org/page)\n![signed](https://example.org/image?id=2)'),['file:///D:/with%20spaces/ref.png','https://example.org/image?id=2']);
  const native = normalizeNativeItem({id:'u',type:'UserMessage',content:[{type:'localImage',path:'C:/input.png'}]}, {}, {timestamp:'2026-10-11T00:00:00Z'});
  assert.equal(native.role,'user'); assert.equal(native.images[0].ref,'C:/input.png');
});

test('external activity and retry errors are separate from the message count', () => {
  const reader=new RolloutReader();
  reader.consume({type:'event_msg',timestamp:'2026-10-11T00:00:00Z',payload:{type:'item_completed',turn_id:'t',item:{type:'UserMessage',id:'u',text:'检查'}}});
  reader.consume({type:'response_item',timestamp:'2026-10-11T00:00:01Z',payload:{type:'function_call',name:'exec_command',call_id:'c',arguments:'{"cmd":"npm test"}'}});
  assert.equal(reader.turns.get('t').activity.command,'npm test');
  reader.consume({type:'event_msg',timestamp:'2026-10-11T00:00:02Z',payload:{type:'error',turn_id:'t',message:'Selected model is at capacity.',will_retry:true}});
  assert.equal(reader.turns.get('t').alert.retrying,true);
  assert.equal(reader.turns.get('t').nativeIds.size,1);
  reader.consume({type:'event_msg',timestamp:'2026-10-11T00:00:03Z',payload:{type:'task_complete',turn_id:'t',error:{message:'Selected model is at capacity.'}}});
  assert.equal(reader.turns.get('t').status,'failed');
  assert.equal(reader.turns.get('t').alert.retrying,false);
  assert.match(reader.turns.get('t').alert.message,/at capacity/);
});

